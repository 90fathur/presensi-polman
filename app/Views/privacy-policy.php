    <h1>Kebijakan Privasi (Privacy Policy)</h1>
    <p><strong>Terakhir Diperbarui:</strong> 29 April 2026</p>
    <p><strong>Aplikasi:</strong> Presensi Polman 2.0</p>
    <p><strong>Pengembang:</strong> Pemerintah Kabupaten Polewali Mandar</p>

    <p>Pemerintah Kabupaten Polewali Mandar ("Kami") berkomitmen untuk melindungi privasi dan keamanan data pengguna ("Anda" atau "Pegawai"). Kebijakan Privasi ini menjelaskan bagaimana Kami mengumpulkan, menggunakan, menyimpan, dan melindungi informasi pribadi Anda saat menggunakan aplikasi <strong>Presensi Polman</strong>.</p>

    <h2>1. Informasi yang Kami Kumpulkan</h2>
    <p>Untuk memastikan aplikasi berjalan dengan baik sesuai dengan fungsinya sebagai sistem absensi elektronik ASN, Kami mengumpulkan data berikut:</p>
    <ul>
        <li><strong>Informasi Pribadi:</strong> Nama Lengkap, Nomor Induk Pegawai (NIP), Jabatan, Unit Kerja (OPD), dan Nomor WhatsApp.</li>
        <li><strong>Data Lokasi (GPS):</strong> Kami mengumpulkan data lokasi perangkat Anda secara *real-time* <strong>hanya pada saat Anda membuka aplikasi dan menekan tombol absen</strong>. Hal ini diperlukan untuk memvalidasi apakah Anda berada di dalam radius kantor yang telah ditentukan (Geofencing) atau area <i>Work From Anywhere</i> (WFA).</li>
        <li><strong>Data Kamera & Biometrik Wajah:</strong> Aplikasi memerlukan akses ke kamera perangkat Anda untuk mengambil foto (selfie) pada saat melakukan pendaftaran wajah <i>(Enrollment)</i> dan pada saat melakukan presensi harian <i>(Liveness Detection)</i>. Kami mengonversi citra wajah Anda menjadi data vektor matematika (Biometric Vector) untuk mencocokkan identitas Anda.</li>
        <li><strong>Informasi Perangkat:</strong> Kami merekam ID Perangkat (Device Token) Anda untuk fitur <i>Device Binding</i> (mengunci akun hanya untuk satu perangkat) demi mencegah kecurangan presensi/joki absen.</li>
        <li><strong>File & Media:</strong> Aplikasi dapat meminta akses ke penyimpanan/galeri jika Anda mengunggah dokumen bukti sakit atau surat tugas luar kota.</li>
    </ul>

    <h2>2. Bagaimana Kami Menggunakan Informasi Anda</h2>
    <p>Data yang dikumpulkan semata-mata digunakan untuk kepentingan tata kelola kepegawaian Pemerintah Kabupaten Polewali Mandar, meliputi:</p>
    <ul>
        <li>Memverifikasi kehadiran Anda setiap hari (Masuk, Siang, Pulang, dan Shift).</li>
        <li>Menghitung akurasi jarak lokasi Anda dengan titik koordinat instansi.</li>
        <li>Mencegah tindak pemalsuan identitas (Anti-Spoofing) menggunakan pengenalan wajah.</li>
        <li>Mengirimkan notifikasi penting terkait jadwal dinas, pengumuman Apel, atau persetujuan izin melalui Push Notification dan WhatsApp.</li>
        <li>Penyusunan laporan kinerja dan kedisiplinan pegawai (E-Kinerja).</li>
    </ul>

    <h2>3. Keamanan Data</h2>
    <div class="highlight">
        <p><strong>Kami tidak membagikan, menjual, atau menyewakan data pribadi, lokasi, maupun biometrik Anda kepada pihak ketiga mana pun di luar kepentingan kedinasan Pemerintah Kabupaten Polewali Mandar.</strong></p>
    </div>
    <p>Kami menerapkan standar keamanan enkripsi data (HTTPS/SSL) selama transmisi dari perangkat Anda ke server Kami. Data sandi (password) disimpan menggunakan algoritma <i>hashing</i> yang kuat. Vektor wajah Anda disimpan sebagai kode angka di dalam database yang aman, bukan sebagai file gambar utuh, guna memastikan privasi tingkat tinggi.</p>

    <h2>4. Penyimpanan dan Penghapusan Data</h2>
    <p>Data presensi Anda disimpan di pusat data (Server) milik Pemerintah Kabupaten Polewali Mandar. Data tersebut akan disimpan selama Anda masih berstatus aktif sebagai pegawai. Jika Anda mutasi, pensiun, atau berhenti bertugas, Anda dapat meminta penghapusan data identitas maupun kunci perangkat dengan menghubungi Administrator Kepegawaian (BKD/OPD) di instansi Anda.</p>

    <h2>5. Persetujuan Akses Perangkat</h2>
    <p>Aplikasi akan meminta izin eksplisit dari Anda sebelum mengakses Kamera, Lokasi, dan Penyimpanan (File). Anda berhak menolak memberikan izin tersebut, namun penolakan tersebut akan mengakibatkan Anda tidak dapat menggunakan fitur utama aplikasi ini (Gagal Absen).</p>

    <h2>6. Perubahan Kebijakan Privasi</h2>
    <p>Kami dapat memperbarui Kebijakan Privasi ini dari waktu ke waktu untuk menyesuaikan dengan regulasi terbaru. Pemberitahuan akan diberikan di dalam aplikasi jika terdapat perubahan material pada kebijakan ini.</p>

